// T-WEB-08: product content rules hold in every frontend text file: source, configs, e2e, scripts, index.html, README (bug B-31).
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

const ROOT = join(__dirname, '..');

const SKIP = new Set(['node_modules', 'dist', 'test-results', 'playwright-report', 'coverage']);

function files(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return SKIP.has(name) ? [] : files(path);
    return /\.(tsx?|m?js|css|html|svg|md|json)$/.test(name) && name !== 'package-lock.json' ? [path] : [];
  });
}

const SOURCES = files(ROOT).filter((path) => !path.endsWith('content.test.ts'));
const read = (path: string) => readFileSync(path, 'utf8');

describe('T-WEB-08 content rules', () => {
  it('has no em dash anywhere (rule 17)', () => {
    const emDash = String.fromCharCode(0x2014);
    for (const path of SOURCES) expect(read(path).includes(emDash), path).toBe(false);
  });

  it('uses none of the banned marketing words (rule 15)', () => {
    const banned = /\b(seamless(ly)?|unlock|elevate|empower|revolutioni[sz]e|supercharge|journey|leverage|robust)\b/i;
    for (const path of SOURCES) expect(banned.exec(read(path))?.[0], path).toBeUndefined();
  });

  it('has no pill-shaped buttons and no gradients (rules 11, 13)', () => {
    for (const path of SOURCES) {
      const text = read(path);
      expect(text.includes('rounded-full'), path).toBe(false);
      expect(/gradient\(|bg-gradient|from-(purple|violet)/.test(text), path).toBe(false);
    }
  });

  it('has no AI or build-tool badge (rule 16) and no secrets (rule 3)', () => {
    for (const path of SOURCES) {
      const text = read(path);
      expect(/made with ai|generated by|built with (claude|gpt|ai)/i.test(text), path).toBe(false);
      expect(/JWT_SECRET|DATABASE_URL|document\.cookie|localStorage/.test(text), path).toBe(false);
    }
  });

  it('reads no environment values except public VITE_ ones (rule 3)', () => {
    for (const path of SOURCES) {
      for (const [, name = ''] of read(path).matchAll(/import\.meta\.env\.([A-Z_]+)/g)) {
        expect(['DEV', 'PROD', 'MODE'].includes(name) || name.startsWith('VITE_'), `${path}: ${name}`).toBe(true);
      }
    }
  });
});
